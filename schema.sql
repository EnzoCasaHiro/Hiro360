-- REFERÊNCIA (MySQL). O servidor cria estas tabelas sozinho quando DB_DRIVER=mysql; este arquivo só documenta.
CREATE TABLE IF NOT EXISTS meta(k VARCHAR(40) PRIMARY KEY, v VARCHAR(255)) CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS docs(
  path VARCHAR(255) PRIMARY KEY,      -- 'colecao/id' (ou 'auditoria/uid/m/AAAAMM')
  col  VARCHAR(200) NOT NULL, id VARCHAR(120) NOT NULL,
  json LONGTEXT, seq BIGINT NOT NULL, del TINYINT NOT NULL DEFAULT 0,
  KEY docs_col(col, del), KEY docs_seq(seq)) CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS users(id VARCHAR(40) PRIMARY KEY, username VARCHAR(60) UNIQUE NOT NULL, name VARCHAR(120) NOT NULL,
  hash VARCHAR(300) NOT NULL, admin TINYINT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1, created VARCHAR(40), last_login VARCHAR(40)) CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS sessions(th VARCHAR(80) PRIMARY KEY, uid VARCHAR(40) NOT NULL, created BIGINT NOT NULL, last BIGINT NOT NULL, KEY s_uid(uid)) CHARACTER SET utf8mb4;
CREATE TABLE IF NOT EXISTS blobs(id VARCHAR(80) PRIMARY KEY, name VARCHAR(300), type VARCHAR(100), size BIGINT, uid VARCHAR(40), created VARCHAR(40)) CHARACTER SET utf8mb4;
